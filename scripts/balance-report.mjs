/**
 * docs/BALANCE.md: what the current content adds up to. Regenerate after any
 * change to the numbers in content/: `npm run balance`.
 */
import fs from 'node:fs'
import path from 'node:path'
import { ROOT } from './lib/env.mjs'
import { data, figures } from './lib/simulate.mjs'

const regionName = (r) => data.regions[r].name
const q = (id) => data.questions.find((x) => x.id === id)
const mean = (xs) => xs.reduce((a, b) => a + b, 0) / xs.length

// Per place: every combination of choices, equally likely.
const rows = []
for (const [r, reg] of Object.entries(data.regions)) {
  const positions = [...Array.from({ length: reg.positions }, (_, i) => i + 1), ...(reg.special ? [reg.special] : [])]
  for (const p of positions) {
    const ids = reg.order.map((s) => (s === 'U' ? `${r}-${p}` : `${r}-${s}`))
    const totals = []
    for (const a of q(ids[0]).choices) for (const b of q(ids[1]).choices) for (const c of q(ids[2]).choices) {
      totals.push({ marks: Math.max(0, a.marks + b.marks + c.marks), fama: a.fama + b.fama + c.fama, nefas: a.nefas + b.nefas + c.nefas })
    }
    rows.push({ region: regionName(r), position: p, title: q(`${r}-${p}`).title, marks: mean(totals.map((x) => x.marks)), min: Math.min(...totals.map((x) => x.marks)), max: Math.max(...totals.map((x) => x.marks)), fama: mean(totals.map((x) => x.fama)), nefas: mean(totals.map((x) => x.nefas)) })
  }
}

// Nefas from shared scenes alone.
const sharedNefas = Object.entries(data.regions).map(([r, reg]) => {
  const ids = reg.order.filter((s) => s !== 'U').map((s) => `${r}-${s}`)
  return { region: regionName(r), nefas: ids.reduce((sum, id) => sum + mean(q(id).choices.map((c) => c.nefas)), 0) }
})

const f = figures({ classes: 400 })
const at30 = f.find((x) => x.classSize === 30 && x.turnIn === 0.4)

const lines = []
lines.push('# Balance (generated)', '')
lines.push(`*Generated by \`scripts/balance-report.mjs\` from \`src/data/sack.json\` (${data.questions.length} scenes). Choices are taken as equally likely; real classes are not random, so read these as the shape of the numbers, not a forecast.*`, '')
lines.push('## A class of thirty', '')
lines.push(`- **Silver:** about **${Math.round(at30.marksPerStudent)} marks** collected per student.`)
lines.push(`- **Nefas:** about **${at30.nefasPerClass.toFixed(1)}** for the class (${at30.nefasPerStudent.toFixed(2)} per student).`)
lines.push(`  - For comparison, the IM's own design (nefas only in the unique scenes, at the live module's values) gives about +9 for thirty.`)
lines.push(`  - The live module as a whole gives about +69.`)
lines.push(`- **Fama:** about **${at30.famaPerStudent >= 0 ? '+' : ''}${at30.famaPerStudent.toFixed(1)}** per student from the sack.`, '')
lines.push('## Nefas and class size', '')
lines.push('The IM subtracts the class total from the endgame score, so the same behaviour costs a class of 60 five times what it costs a class of 12. The last column shows the alternative proposed in docs/RULINGS.md: nefas per ten students, which does not grow with the class.', '')
lines.push('| Students | Class total (IM rule) | Per ten students (proposed) |', '|---|---|---|')
for (const x of f.filter((y) => y.turnIn === 0.4)) lines.push(`| ${x.classSize} | ${x.nefasPerClass >= 0 ? '+' : ''}${x.nefasPerClass.toFixed(1)} | ${x.nefasPerStudent >= 0 ? '+' : ''}${(x.nefasPerStudent * 10).toFixed(1)} |`)
lines.push('')
lines.push('## Venice', '')
lines.push('| Students | Share handed in | Venice paid in | Silver per student | Class nefas |')
lines.push('|---|---|---|---|---|')
for (const x of f) lines.push(`| ${x.classSize} | ${Math.round(x.turnIn * 100)}% | ${Math.round(x.paid * 100)}% of classes | ${Math.round(x.marksPerStudent)} | ${x.nefasPerClass >= 0 ? '+' : ''}${x.nefasPerClass.toFixed(1)} |`)
lines.push('')
lines.push('## Nefas from the shared scenes', '')
lines.push('Expected nefas a student picks up from their region\'s two shared scenes, choosing at random:', '')
lines.push('| Region | Shared-scene nefas |', '|---|---|')
for (const s of sharedNefas) lines.push(`| ${s.region} | ${s.nefas >= 0 ? '+' : ''}${s.nefas.toFixed(2)} |`)
lines.push('')
lines.push('## By place', '')
lines.push('Each row averages all 64 ways through that place.', '')
lines.push('| Region | Pos. | Scene | Mean marks | Min | Max | Mean fama | Mean nefas |')
lines.push('|---|---|---|---|---|---|---|---|')
for (const r of rows) lines.push(`| ${r.region} | ${r.position} | ${r.title} | ${Math.round(r.marks)} | ${r.min} | ${r.max} | ${r.fama >= 0 ? '+' : ''}${r.fama.toFixed(1)} | ${r.nefas >= 0 ? '+' : ''}${r.nefas.toFixed(1)} |`)
fs.writeFileSync(path.join(ROOT, 'docs', 'BALANCE.md'), lines.join('\n') + '\n')
console.log(`balance-report: class of 30 at 40% handed in: ${Math.round(at30.marksPerStudent)} marks/student, nefas ${at30.nefasPerClass.toFixed(1)}, Venice paid ${Math.round(at30.paid * 100)}%`)
